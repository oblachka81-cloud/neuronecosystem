const tgLang = window.Telegram?.WebApp?.initDataUnsafe?.user?.language_code || 'en';
const supportedLangs = ['ru', 'en', 'fr', 'es'];
let currentLang = localStorage.getItem('neuron_lang') || (supportedLangs.includes(tgLang) ? tgLang : 'en');
if (!TRANSLATIONS[currentLang]) currentLang = 'en';
let t = TRANSLATIONS[currentLang];

function setLang(lang) {
  currentLang = lang;
  t = TRANSLATIONS[lang] || TRANSLATIONS.en;
  localStorage.setItem('neuron_lang', lang);

  if (userId) {
    authFetch(`${BASE_URL}/api/user/nickname`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ language_code: lang })
    }).catch(() => {});
  }

  document.getElementById('langBtnImg').src = 'main/btn_lang_' + lang + '.webp';
  document.getElementById('tabGameImg').src = 'main/tab_game_' + currentLang + '.webp';
  document.getElementById('tabLeaderImg').src = 'main/tab_leaderboard_' + currentLang + '.webp';
  document.getElementById('tabWalletImg').src = 'main/tab_wallet_' + currentLang + '.webp';
  document.getElementById('tabProfileImg').src = 'main/tab_profile_' + currentLang + '.webp';
  document.getElementById('footerEl').textContent = t.footer;
  document.getElementById('langModalTitle').textContent = t.selectLang;
  document.getElementById('tabShopImg').src = 'main/tab_shop_' + currentLang + '.webp';
  document.getElementById('tabBankImg').src = 'main/tab_bank_' + currentLang + '.webp';
  document.getElementById('tabCasinoImg').src = 'main/tab_impulse_' + currentLang + '.webp';
  document.getElementById('tabExchangeImg').src = 'main/tab_exchange_' + lang + '.webp';
  document.getElementById('supportBtnImg').src = 'main/support_btn_' + lang + '.webp';
  if (window.updateFortunaSpinBtn) window.updateFortunaSpinBtn();
  updateTonModal();
  updateScoresUI(currentState.totalScore);
  updateGamesLeftUI(currentState.freeGamesLeft);
  renderLangGrid();
  closeLangModal();
  if (currentTab === 'leaderboard') loadLeaderboard();
  else if (currentTab === 'wallet') showWalletPanel();
  else if (currentTab === 'profile') loadProfilePanel();
  else if (currentTab === 'support') loadSupportPanel();
  else loadWelcome();
}
  

function updateTonModal() {
  const el = id => document.getElementById(id);
  if (el('tonModalTitle'))       el('tonModalTitle').textContent    = t.tonModalTitle;
  if (el('tonModalText'))        el('tonModalText').innerHTML       = t.tonModalText;
  if (el('tonModalWarning'))     el('tonModalWarning').textContent  = t.tonModalWarning;
  if (el('tonModalCheckLabel'))  el('tonModalCheckLabel').innerHTML = t.tonModalCheckLabel;
  if (el('tonModalCancelBtn'))   el('tonModalCancelBtn').textContent= t.tonModalCancel;
  if (el('tonModalConfirmBtn'))  el('tonModalConfirmBtn').textContent= t.tonModalConfirm;
}

function renderLangGrid() {
  const grid = document.getElementById('langGrid');
  grid.innerHTML = Object.entries(TRANSLATIONS).map(([code, tr]) =>
    `<button class="lang-opt${currentLang === code ? ' active' : ''}" onclick="setLang('${code}')">${tr.flag} ${tr.name}</button>`
  ).join('');
}

function openLangModal() {
  document.getElementById('langModalTitle').textContent = t.selectLang;
  renderLangGrid();
  document.getElementById('langOverlay').classList.add('open');
}

function closeLangModal(e) {
  if (!e || e.target === document.getElementById('langOverlay'))
    document.getElementById('langOverlay').classList.remove('open');
}
